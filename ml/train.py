from textpipe import Model, analyse, load_signals

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data" / "processed"
OUT = ROOT / "apps" / "web" / "public" / "model"
ART = Path(__file__).resolve().parent / "artifacts"
NGRAM = (2, 5)
MIN_DF = 3
KEEP = 60000          # features kept after pruning (model-size control; the exported file must stay under 2 MB)
SIG_SCALE = 1.0
VERSION = "2026-11-23.4"
SEED = 7

# ---- sample weights (see sample_weights) ------------------------------------------------------------------------
GEN_SOURCES = ("team_trap_genuine_v1", "team_scam_gap_v1")   # generated by gen_team_data.py (templated, small, high value per row)
GEN_SHARE = 0.15       # trap_genuine + scam_gap together carry at most this share of the weighted training mass
SOURCE_CAP = 0.30      # no other single source carries more than this share of the total weighted mass
FAMILY_N = 40          # a template family (group) with n > FAMILY_N rows is damped by sqrt(FAMILY_N / n)
LANG_WEIGHT = 1.8      # Hindi / Hinglish rows count 1.8x (little data, the realistic target language)
PUBLIC_BASE = 0.8      # the two big templated public sets (cloveai, bolewara_uci) start slightly below 1
TEAM_BASE = 1.5        # other hand-written / template team sources start at 1.5

# ---- band policy, chosen on the realistic validation slice (team-written rows and all Hindi/Hinglish rows) -------
RECALL_TARGET = 0.97   # suspicious cut: the HIGHEST cut that still catches >= 97% of scams (fewest false flags)
PRECISION_TARGET = 0.97  # scam cut: the LOWEST cut whose flagged messages are >= 97% scams
BAND_MIN = 0.15        # the suspicious band must be at least this wide, so uncertain messages are never shown as certain
SCAM_CUT_FALLBACK = 0.5  # if the precision target is unreachable: the calibrated midpoint (the 2026-11-23.2 code used 0.85, which would put the suspicious cut at 0.60)
C_TOLERANCE = 0.0002   # choose the smallest C whose validation AP is within this of the best (prefer stronger regularisation)
MIN_FLAGGED = 10       # a cut must flag at least this many slice rows for its precision to count
BOOT = 400             # family-level bootstrap resamples for the 95% lower bounds of recall / precision
CV_FOLDS = 4           # group-held-out folds for the out-of-family predictions used to choose the cuts
CV_REPEATS = 10        # independent fold assignments pooled together (one assignment alone moves the cuts by 0.1-0.4)
GRID = np.round(np.arange(0.02, 0.99, 0.01), 2)


# ---- training-set-only augmentation: Hinglish has no standard spelling -------------------------------
def spell_variant(text: str, rng: random.Random) -> str:
    subs = [("aa", "a"), ("ee", "i"), ("oo", "u"), ("kh", "k"), ("ph", "f"), ("ai", "ay"), ("hai", "he"), ("nahi", "nahin"), ("karein", "karen"),
            ("aapka", "apka"), ("aapki", "apki"), ("abhi", "abi"), ("turant", "turant"), ("bhejo", "bhejiye")]
    out = text
    for a, b in rng.sample(subs, k=3):
        if rng.random() < 0.7:
            out = out.replace(a, b)
    if rng.random() < 0.3:
        out = out.replace(" ", "  ", 1)
    return out


def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def refuse_unsafe_corpus(df: pd.DataFrame, allow_small: bool = False) -> None:
    """Stop (exit status 1 or 2) instead of training on a truncated corpus or on frozen evaluation text."""
    if len(df) < MIN_EXTERNAL_ROWS and not allow_small:
        print(f"ERROR: the corpus has only {len(df)} rows (a full corpus has about 23,000). The git-ignored datasets are probably missing in "
              "this worktree: fix the junctions and run build_corpus.py again. Refusing to train.", file=sys.stderr)
        sys.exit(2)
    index, warns = leak_check.build_index(FROZEN, ROOT)
    for w in warns:
        print(f"WARNING: {w}", file=sys.stderr)
    if not FROZEN.is_dir():
        print("!" * 78 + f"\nWARNING: frozen evaluation directory {FROZEN} is missing: only the challenge sets could be checked for leaks.\n" + "!" * 78,
              file=sys.stderr)
    mask, detail = leak_check.scan_dataframe(df, index)
    if mask.any():
        print(f"ERROR: {int(mask.sum())} training-corpus rows match frozen evaluation texts (rows {sorted(detail)[:10]}...). "
              "Run build_corpus.py again (it removes them) or leak_check.py --drop on the source CSVs. Refusing to train.", file=sys.stderr)
        sys.exit(1)
    print(f"leak guard: 0 of {len(df)} corpus rows match the {sum(index.sizes.values())} frozen evaluation texts (exact / signature / Jaccard >= 0.85)")


# ---- sample weights ---------------------------------------------------------------------------------------------
def sample_weights(tr: pd.DataFrame, gen_share: float = GEN_SHARE, source_cap: float = SOURCE_CAP, family_n: int = FAMILY_N):
    """Per-row weights for the training rows (including the Hinglish spelling variants) and a report of the resulting mass shares.

    1. base weight by source: public cloveai / bolewara_uci 0.8; other team-written sources 1.5; everything else 1.
    2. family damping: a template family (`group`) with n > family_n rows is multiplied by sqrt(family_n / n), so one templated family
       of hundreds of near-identical public messages cannot outvote the rest.
    3. language: Hindi / Hinglish rows x1.8.
    4. source cap: no source other than the generated ones may carry more than `source_cap` of the TOTAL mass (water-filling on the
       non-generated pool, whose total is (1 - gen_share) of the final mass).
    5. generated data: trap_genuine + scam_gap are rescaled so that together they carry exactly `gen_share` of the total mass
       (the handoff ceiling is about 15%). They are small and templated, so unbounded weights would let them dominate.
    """
    src = tr.source.values
    w = np.ones(len(tr))
    w *= np.where(np.isin(src, ["cloveai", "bolewara_uci"]), PUBLIC_BASE, 1.0)
    w *= np.where(pd.Series(src).str.startswith("team_").values & ~np.isin(src, GEN_SOURCES), TEAM_BASE, 1.0)
    n_g = tr.groupby("group").group.transform("size").values
    w *= np.minimum(1.0, np.sqrt(family_n / n_g))
    w *= np.where(tr.lang.values != "english", LANG_WEIGHT, 1.0)

    is_gen = np.isin(src, GEN_SOURCES)
    pool_src = [s for s in sorted(set(src[~is_gen]))]
    mass = {s: float(w[src == s].sum()) for s in pool_src}
    max_share = source_cap / (1.0 - gen_share) if gen_share < 1 else 1.0          # as a share of the non-generated pool
    for _ in range(20):
        total = sum(mass.values())
        over = [s for s in pool_src if mass[s] > max_share * total + 1e-9]
        if not over:
            break
        for s in over:
            others = total - mass[s]
            mass[s] = max_share * others / (1.0 - max_share)
    for s in pool_src:
        m0 = float(w[src == s].sum())
        if m0 > 0:
            w[src == s] *= mass[s] / m0
    pool_total = float(w[~is_gen].sum())
    gen_mass = gen_share / (1.0 - gen_share) * pool_total if is_gen.any() else 0.0
    if is_gen.any():
        w[is_gen] *= gen_mass / float(w[is_gen].sum())
    total = float(w.sum())
    report = {"gen_share_target": gen_share, "source_cap": source_cap, "family_n": family_n, "total_mass": round(total, 1),
              "mass_share_by_source": {s: round(float(w[src == s].sum()) / total, 4) for s in sorted(set(src))},
              "rows_by_source": {s: int((src == s).sum()) for s in sorted(set(src))},
              "mean_weight_by_source": {s: round(float(w[src == s].mean()), 3) for s in sorted(set(src))},
              "gen_share_actual": round(float(w[is_gen].sum()) / total, 4)}
    return w, report


# ---- features ---------------------------------------------------------------------------------------------------
def prepare(df: pd.DataFrame, sg: dict, log=print) -> dict:
    """Analyse the training rows (+ Hinglish spelling variants) and the validation rows; fit the vocabulary and idf on training only."""
    t0 = time.time()
    sig_ids = [s["id"] for s in sg["signals"]]
    tr = df[df.split == "train"].reset_index(drop=True)
    rng = random.Random(SEED)
    aug = tr[tr.lang == "hinglish"].sample(frac=0.6, random_state=1).copy()
    aug["text"] = [spell_variant(t, rng) for t in aug.text]
    tr_aug = pd.concat([tr, aug], ignore_index=True)
    va = df[df.split == "val"].reset_index(drop=True)
    log(f"train={len(tr)} (+{len(aug)} spelling variants) val={len(va)}")

    def prep(texts):
        feats, sigs = [], []
        for t in texts:
            _, _, f, s = analyse(t, sg, NGRAM)
            feats.append(f)
            sigs.append({x["id"] for x in s})
        return feats, sigs

    F_tr, S_tr = prep(tr_aug.text)
    F_va, S_va = prep(va.text)
    log(f"analysed in {time.time() - t0:.0f}s")
    dfc: Counter = Counter()
    for f in F_tr:
        dfc.update(f.keys())
    N = len(F_tr)
    vocab_all = sorted(k for k, c in dfc.items() if c >= MIN_DF)
    idf_all = {k: math.log((1 + N) / (1 + dfc[k])) + 1.0 for k in vocab_all}
    return {"tr": tr, "aug": aug, "tr_aug": tr_aug, "va": va, "F_tr": F_tr, "S_tr": S_tr, "F_va": F_va, "S_va": S_va,
            "vocab_all": vocab_all, "idf_all": idf_all, "sig_ids": sig_ids}


def build(D: dict, F, S, vocab):
    idx = {k: i for i, k in enumerate(vocab)}
    idf_all = D["idf_all"]
    rows, cols, vals = [], [], []
    for r, f in enumerate(F):
        items = [(idx[k], (1.0 + math.log(c)) * idf_all[k]) for k, c in f.items() if k in idx]
        nrm = math.sqrt(sum(v * v for _, v in items)) or 1.0
        for j, v in items:
            rows.append(r); cols.append(j); vals.append(v / nrm)
    X = csr_matrix((vals, (rows, cols)), shape=(len(F), len(vocab)))
    Dm = np.array([[1.0 if s in row else 0.0 for s in D["sig_ids"]] for row in S]).reshape(len(S), len(D["sig_ids"])) * SIG_SCALE
    return hstack([X, csr_matrix(Dm)]).tocsr()


def lr(C):
    return LogisticRegression(C=C, class_weight="balanced", max_iter=3000, solver="liblinear", random_state=SEED)


def fit(D: dict, w: np.ndarray, C: float | None = None, log=print) -> dict:
    """Fit on the full vocabulary (choosing C on validation AP unless given), prune to the KEEP strongest text features, refit, calibrate."""
    y_tr, y_va = D["tr_aug"].label.values, D["va"].label.values
    vocab_all = D["vocab_all"]
    X_tr, X_va = build(D, D["F_tr"], D["S_tr"], vocab_all), build(D, D["F_va"], D["S_va"], vocab_all)
    if C is None:
        tried = []
        for c in (0.3, 1, 3, 10, 30):
            m = lr(c).fit(X_tr, y_tr, sample_weight=w)
            ap = average_precision_score(y_va, m.decision_function(X_va))
            log(f"  C={c:<5} val AP={ap:.4f}")
            tried.append((ap, c, m))
        top = max(t[0] for t in tried)
        _, C, m_full = min((t for t in tried if t[0] >= top - C_TOLERANCE), key=lambda t: t[1])
    else:
        m_full = lr(C).fit(X_tr, y_tr, sample_weight=w)
    nt = len(vocab_all)
    order = np.argsort(-np.abs(m_full.coef_[0][:nt]), kind="stable")[:KEEP]
    vocab = sorted(vocab_all[i] for i in order)
    X_tr, X_va = build(D, D["F_tr"], D["S_tr"], vocab), build(D, D["F_va"], D["S_va"], vocab)
    m = lr(C).fit(X_tr, y_tr, sample_weight=w)
    z_va = m.decision_function(X_va)
    cal = LogisticRegression(C=1e6, max_iter=1000).fit(z_va.reshape(-1, 1), y_va)       # Platt scaling on the raw score
    a, b = float(cal.coef_[0][0]), float(cal.intercept_[0])
    return {"m": m, "C": C, "vocab": vocab, "z_va": z_va, "a": a, "b": b, "p_va": sigmoid(a * z_va + b), "X_tr": X_tr,
            "ap": float(average_precision_score(y_va, z_va)), "auc": float(roc_auc_score(y_va, z_va))}


def cross_fit_realistic(D: dict, w: np.ndarray, fr: dict, folds: int = CV_FOLDS, seed: int = SEED, log=print):
    """Out-of-family predictions for the realistic TRAINING rows (team-written or non-English): the realistic groups are split into `folds`
    parts; each part is predicted by a model trained without it (same features, C, weights and calibration as the final model).
    Returns (p, y, group) for the original (non-augmented) realistic training rows. Uses training rows only; no frozen data."""
    tr_aug = D["tr_aug"]
    y = tr_aug.label.values
    real = realistic_mask(tr_aug)
    groups = sorted(tr_aug[real].group.unique())
    random.Random(seed).shuffle(groups)
    fold_of = {g: i % folds for i, g in enumerate(groups)}
    fold_row = np.array([fold_of.get(g, -1) if r else -1 for g, r in zip(tr_aug.group.values, real)])
    p = np.full(len(tr_aug), np.nan)
    for k in range(folds):
        held = fold_row == k
        m = lr(fr["C"]).fit(fr["X_tr"][~held], y[~held], sample_weight=w[~held])
        p[held] = sigmoid(fr["a"] * m.decision_function(fr["X_tr"][held]) + fr["b"])
        log(f"  cross-fit fold {k + 1}/{folds}: {int(held.sum())} held-out realistic rows")
    n = len(D["tr"])                                    # the first n rows are the originals; the rest are spelling variants of Hinglish rows
    keep = real[:n]
    return p[:n][keep], y[:n][keep], tr_aug.group.values[:n][keep]


# ---- thresholds and diagnostics ---------------------------------------------------------------------------------
def realistic_mask(va: pd.DataFrame) -> np.ndarray:
    return (va.source.str.startswith("team_") | (va.lang != "english")).values


def pick_cuts(p: np.ndarray, y: np.ndarray, groups=None, weights=None, use_lcb: bool = False, log=print) -> dict:
    """Scam cut = lowest cut with precision >= 0.97; suspicious cut = highest cut with recall >= 0.97 (both on a realistic slice: p, y, optional
    row weights). These are point estimates (the rule of the 2026-11-23.2 model). With use_lcb=True each target must instead hold at the 5th
    percentile of a family-level bootstrap (`groups`, default one family per row); the 95% lower bounds are always computed and returned
    for reporting. If the two cuts are closer than BAND_MIN the suspicious cut is moved down to keep a real 'suspicious' band; if no cut
    reaches the precision target the scam cut is the calibrated midpoint."""
    yr, pr = np.asarray(y), np.asarray(p)
    g_ids = pd.factorize(np.asarray(groups) if groups is not None else np.arange(len(yr)))[0]
    nf = g_ids.max() + 1
    pos = (yr == 1)
    wt = np.ones(len(yr)) if weights is None else np.asarray(weights, dtype=float)
    pos_tot = np.bincount(g_ids[pos], weights=wt[pos], minlength=nf)
    pos_ge = np.stack([np.bincount(g_ids[pos & (pr >= t)], weights=wt[pos & (pr >= t)], minlength=nf) for t in GRID], axis=1)      # families x cuts
    neg_ge = np.stack([np.bincount(g_ids[~pos & (pr >= t)], weights=wt[~pos & (pr >= t)], minlength=nf) for t in GRID], axis=1)
    m = np.random.RandomState(SEED).multinomial(nf, np.full(nf, 1.0 / nf), size=BOOT).astype(float)             # how often each family is drawn
    pt, pg, ng = m @ pos_tot, m @ pos_ge, m @ neg_ge                                                              # BOOT, BOOT x cuts, BOOT x cuts
    rec_b = pg / np.maximum(pt[:, None], 1e-12)
    flagged_rows = np.stack([(pr >= t).sum() for t in GRID])                                                       # unweighted row counts per cut
    prec_b = np.where(flagged_rows >= MIN_FLAGGED, pg / np.maximum(pg + ng, 1e-12), 0.0)   # a cut that flags (almost) nothing proves nothing
    rec_lcb, prec_lcb = np.percentile(rec_b, 5, axis=0), np.percentile(prec_b, 5, axis=0)
    rec_pt = pos_ge.sum(0) / max(pos_tot.sum(), 1e-12)
    prec_pt = np.where(flagged_rows >= MIN_FLAGGED, pos_ge.sum(0) / np.maximum(pos_ge.sum(0) + neg_ge.sum(0), 1e-12), 0.0)
    rec = lambda t: float(rec_pt[int(np.argmin(np.abs(GRID - t)))])
    prec = lambda t: float(prec_pt[int(np.argmin(np.abs(GRID - t)))])
    ok_p = [t for t, v in zip(GRID, prec_lcb if use_lcb else prec_pt) if v >= PRECISION_TARGET]
    scam = min(ok_p) if ok_p else SCAM_CUT_FALLBACK
    if not ok_p:
        log(f"WARNING: no cut reaches precision {PRECISION_TARGET} on the realistic slice; using the calibrated midpoint {scam}")
    ok_s = [t for t, v in zip(GRID, rec_lcb if use_lcb else rec_pt) if v >= RECALL_TARGET]
    susp = max(ok_s) if ok_s else 0.15
    if not ok_s:
        log(f"WARNING: no cut reaches recall {RECALL_TARGET}; using {susp}")
    raw_susp = susp
    if susp > scam - BAND_MIN:                       # keep a real "suspicious" band (continuous, unlike the 2026-11-23.2 rule scam - 0.25)
        susp = max(0.05, round(scam - BAND_MIN, 2))
    curve = [{"cut": float(t), "recall": round(rec(t), 4), "recall_lcb95": round(float(rec_lcb[i]), 4), "precision": round(prec(t), 4),
              "precision_lcb95": round(float(prec_lcb[i]), 4), "false_alarm": round(float((pr[yr == 0] >= t).mean()), 4)}
             for i, t in enumerate(GRID) if i % 3 == 0]
    return {"suspicious": float(susp), "scam": float(scam), "recall_at_susp": rec(susp), "precision_at_scam": prec(scam),
            "raw_suspicious_cut_for_recall_target": float(raw_susp), "band_adjusted": bool(raw_susp != susp), "n_real": int(len(y)), "curve": curve}


def val_diagnostics(va: pd.DataFrame, p: np.ndarray, cuts: dict, log=print) -> dict:
    """Validation-only tables: per language, per source, genuine families still flagged, scam families still missed."""
    y = va.label.values
    s, c = cuts["suspicious"], cuts["scam"]
    flagged = p >= s
    d: dict = {"per_language": {}, "per_source": {}, "genuine_families": [], "scam_families": []}
    for name, key in (("per_language", "lang"), ("per_source", "source")):
        for k, g in va.groupby(key):
            i = g.index.values
            gy = y[i]
            d[name][k] = {"n": int(len(i)), "scam": int(gy.sum()), "recall@susp": round(float(flagged[i][gy == 1].mean()), 4) if (gy == 1).any() else None,
                          "false_alarm@susp": round(float(flagged[i][gy == 0].mean()), 4) if (gy == 0).any() else None,
                          "false_alarm@scam_cut": round(float((p[i][gy == 0] >= c).mean()), 4) if (gy == 0).any() else None}
    for g, sub in va[va.source.str.startswith("team_")].groupby("group"):
        i = sub.index.values
        gy = y[i]
        if (gy == 0).all():
            fl = int(flagged[i].sum())
            d["genuine_families"].append({"group": g, "source": sub.source.iloc[0], "n": int(len(i)), "flagged": fl, "max_p": round(float(p[i].max()), 3)})
        elif (gy == 1).all():
            ms = int((~flagged[i]).sum())
            d["scam_families"].append({"group": g, "source": sub.source.iloc[0], "n": int(len(i)), "missed": ms, "min_p": round(float(p[i].min()), 3)})
    d["genuine_families"].sort(key=lambda r: (-r["flagged"] / r["n"], -r["n"]))
    d["scam_families"].sort(key=lambda r: (-r["missed"] / r["n"], -r["n"]))
    return d


def print_diagnostics(d: dict, cuts: dict, log=print):
    log(f"cuts: suspicious={cuts['suspicious']:.2f} (recall {cuts['recall_at_susp']:.3f} on the {cuts['n_real']}-row realistic slice), "
        f"scam={cuts['scam']:.2f} (precision {cuts['precision_at_scam']:.3f}); raw recall-97% cut {cuts['raw_suspicious_cut_for_recall_target']:.2f}"
        + (" (moved down to keep a 0.15 band)" if cuts["band_adjusted"] else ""))
    log("per language (validation): " + "; ".join(f"{k}: n={v['n']} recall={v['recall@susp']} FA={v['false_alarm@susp']}" for k, v in d["per_language"].items()))
    log("per source (validation, at the suspicious cut): " + "; ".join(f"{k}: n={v['n']} rec={v['recall@susp']} FA={v['false_alarm@susp']}" for k, v in d["per_source"].items()))
    bad = [r for r in d["genuine_families"] if r["flagged"]]
    log(f"genuine families still flagged (validation): {len(bad)} of {len(d['genuine_families'])}: " + "; ".join(f"{r['group']} {r['flagged']}/{r['n']}" for r in bad[:15]))
    bad = [r for r in d["scam_families"] if r["missed"]]
    log(f"scam families still missed (validation): {len(bad)} of {len(d['scam_families'])}: " + "; ".join(f"{r['group']} {r['missed']}/{r['n']}" for r in bad[:15]))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-small", action="store_true", help="skip the corpus-size refusal (unit tests only)")
    ap.add_argument("--gen-share", type=float, default=GEN_SHARE, help="share of the weighted mass carried by trap_genuine + scam_gap (handoff ceiling 0.15)")
    ap.add_argument("--source-cap", type=float, default=SOURCE_CAP)
    ap.add_argument("--ship", action="store_true", help="write model.json (and the signals / domains copies) into apps/web/public/model, i.e. replace the model "
                    "the app uses. Without it the model is written to ml/artifacts/candidate/ only. Use it only after evaluate.py --measure meets the acceptance rules")
    ap.add_argument("--no-export", action="store_true", help="train and print validation diagnostics but write nothing to apps/web")
    ap.add_argument("--out-dir", type=Path, default=None, help="write only model.json, into this folder (a candidate for evaluate.py --model), not into apps/web")
    ap.add_argument("--C", type=float, default=None, help="fix the regularisation strength instead of choosing it on validation (experiments)")
    args = ap.parse_args(argv)
    t0 = time.time()
    df = pd.read_csv(PROC / "corpus.csv")
    refuse_unsafe_corpus(df, args.allow_small)
    sg = load_signals()
    D = prepare(df, sg)
    tr_aug, va = D["tr_aug"], D["va"]
    w, wrep = sample_weights(tr_aug, args.gen_share, args.source_cap)
    print(f"sample weights: generated share {wrep['gen_share_actual']:.3f} (ceiling 0.15); mass share by source {wrep['mass_share_by_source']}", flush=True)

    fr = fit(D, w, C=args.C)
    C, vocab, m = fr["C"], fr["vocab"], fr["m"]
    print(f"C={C}; pruned to {len(vocab)} features; val AP={fr['ap']:.4f} AUC={fr['auc']:.4f}", flush=True)
    y_va, p_va, z_va = va.label.values, fr["p_va"], fr["z_va"]
    # Band cuts. The realistic validation slice alone is small (~400 rows) and a few whole families swing the cuts, and scores are nearly
    # bimodal, so one cross-fit alone also moves them by 0.1-0.4. The policy is therefore applied ONCE to a larger, steadier slice:
    # the realistic validation rows plus out-of-family (group-held-out) predictions for the realistic training rows, pooled over
    # CV_REPEATS independent fold assignments, with rows weighted exactly like the training mass (so the deliberately adversarial
    # generated families cannot set the cuts alone). Both the plain validation-slice result and the chosen one are printed and stored.
    rv = realistic_mask(va)
    trn = D["tr"]
    real_tr = realistic_mask(trn)
    cols = ["source", "group", "lang", "label"]
    slice_df = pd.concat([trn[real_tr][cols], va[rv][cols]], ignore_index=True)
    sw, _ = sample_weights(slice_df, args.gen_share, args.source_cap)
    n_oof = int(real_tr.sum())
    sw_val, _ = sample_weights(va[rv][cols].reset_index(drop=True), args.gen_share, args.source_cap)
    cuts_val = pick_cuts(p_va[rv], y_va[rv], groups=va.group.values[rv], weights=sw_val)
    ps, ys, gs, ws = [p_va[rv]], [y_va[rv]], [va.group.values[rv]], [sw[n_oof:]]
    for k in range(CV_REPEATS):
        p_k, y_k, g_k = cross_fit_realistic(D, w, fr, seed=SEED + 100 * k)
        ps.append(p_k); ys.append(y_k); gs.append(g_k); ws.append(sw[:n_oof] / CV_REPEATS)
    cuts = pick_cuts(np.concatenate(ps), np.concatenate(ys), groups=np.concatenate(gs), weights=np.concatenate(ws))
    print(f"cuts on the realistic validation slice alone (not used): suspicious={cuts_val['suspicious']:.2f} scam={cuts_val['scam']:.2f} "
          f"({cuts_val['n_real']} rows); cuts used (validation + out-of-family training rows pooled over {CV_REPEATS} fold assignments, {cuts['n_real']} rows): "
          f"suspicious={cuts['suspicious']:.2f} scam={cuts['scam']:.2f}")
    diag = val_diagnostics(va, p_va, cuts)
    print(f"calibration a={fr['a']:.3f} b={fr['b']:.3f}")
    print_diagnostics(diag, cuts)

    coef = m.coef_[0]
    sig_ids = D["sig_ids"]
    model = {
        "version": VERSION, "signals_version": sg["version"], "char_ngrams": list(NGRAM), "sig_scale": SIG_SCALE,
        "intercept": round(float(m.intercept_[0]), 6), "calibration": {"a": round(fr["a"], 6), "b": round(fr["b"], 6)},
        "thresholds": {"suspicious": cuts["suspicious"], "scam": cuts["scam"]},
        "features": vocab, "idf": [round(D["idf_all"][k], 5) for k in vocab], "coef": [round(float(c), 6) for c in coef[:len(vocab)]],
        "signal_coef": {s: round(float(c), 6) for s, c in zip(sig_ids, coef[len(vocab):])},
        "meta": {"C": C, "min_df": MIN_DF, "keep": KEEP, "n_train": int(len(D["tr"])), "n_aug": int(len(D["aug"])), "n_val": int(len(va)),
                 "seed": SEED, "gen_share": args.gen_share, "source_cap": args.source_cap, "family_n": FAMILY_N,
                 "cuts": {"slice_rows": cuts["n_real"], "suspicious_recall": round(cuts["recall_at_susp"], 4), "scam_precision": round(cuts["precision_at_scam"], 4),
                          "policy": "scam cut: lowest with precision >= 0.97, suspicious cut: highest with recall >= 0.97, 95% lower bounds over families, "
                                    "realistic validation rows + out-of-family training rows; scam cut 0.5 if unreachable; band >= 0.15"}},
    }
    ART.mkdir(exist_ok=True)
    report = {"C": C, "features": len(vocab), "val_ap": fr["ap"], "val_auc": fr["auc"], "thresholds": model["thresholds"], "weights": wrep,
              "cuts": cuts, "cuts_validation_slice_only": cuts_val, "diagnostics": diag}
    (ART / "train_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    text = json.dumps(model, ensure_ascii=False, separators=(",", ":"))
    if args.no_export:
        print(f"--no-export: model.json would be {len(text.encode('utf-8')) / 1e6:.2f} MB; nothing written to apps/web (report in {ART / 'train_report.json'})")
    elif args.out_dir is not None or not args.ship:
        out_dir = args.out_dir or ART / "candidate"
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "model.json").write_text(text, encoding="utf-8")
        print(f"candidate written to {out_dir / 'model.json'} ({len(text.encode('utf-8')) / 1e6:.2f} MB); apps/web untouched. "
              "Score it with: python evaluate.py --model <that file>; replace the app's model only with --ship")
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / "model.json").write_text(text, encoding="utf-8")
        shutil.copy(Path(__file__).parent / "signals.json", OUT / "signals.json")
        shutil.copy(Path(__file__).parent / "domains.json", OUT / "domains.json")
        (ROOT / "apps" / "web" / "src" / "detector").mkdir(parents=True, exist_ok=True)
        shutil.copy(Path(__file__).parent / "domains.json", ROOT / "apps" / "web" / "src" / "detector" / "domains.json")
        size = (OUT / "model.json").stat().st_size
        print(f"exported model.json: {size / 1e6:.2f} MB ({len(vocab)} features) in {time.time() - t0:.0f}s")
        if size >= 2_000_000:
            print("ERROR: model.json is 2 MB or larger", file=sys.stderr)
            sys.exit(3)

    # rounding check: reload through the reference scorer and compare with sklearn on a sample
    mm = Model(model)
    chk = va.sample(200, random_state=0)
    zs = np.array([mm.score(t, sg)["z"] for t in chk.text])
    print(f"reference-scorer vs sklearn max |dz| on 200 val messages: {np.abs(zs - z_va[chk.index.values]).max():.2e}")


if __name__ == "__main__":
    main()
