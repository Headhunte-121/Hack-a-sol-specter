"""Train the on-device scam classifier: TF-IDF (char n-grams inside words + word 1-2 grams) + signal flags -> logistic regression.

Everything that is chosen (C, pruning size, calibration, band thresholds, sample weights) is chosen on the VALIDATION split only.
The test split and the challenge / blind / probe sets are scored by evaluate.py, a few times only, afterwards.
Writes apps/web/public/model/model.json and signals.json (the files the phone reads) and ml/artifacts/ (git-ignored diagnostics).
Usage: python train.py [--ship] [--gen-share 0.15] [--source-cap 0.30] [--no-export]
Without --ship the model goes to ml/artifacts/candidate/ and the app keeps the model it has.
Reproducible: every random choice is seeded (SEED); a re-run on the same corpus writes a byte-identical model.json.
"""
