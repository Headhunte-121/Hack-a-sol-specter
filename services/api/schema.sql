-- Suraksha Reports API: PostgreSQL Schema (Production / Supabase)
-- Idempotent: can be executed multiple times without error.

CREATE TABLE IF NOT EXISTS scam_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_hour TEXT NOT NULL,          -- UTC ISO hour (e.g. 2026-11-23T10:00:00Z)
  scam_category TEXT NOT NULL,
  channel TEXT NOT NULL,
  region_code TEXT NOT NULL,
  risk_band TEXT NOT NULL,
  source TEXT NOT NULL,                -- 'app' or 'seed'
  client_batch_id TEXT NOT NULL UNIQUE -- idempotent batch token
);

CREATE TABLE IF NOT EXISTS region_lookup (
  region_code TEXT PRIMARY KEY,
  name_en TEXT,
  name_hi TEXT,
  parent_region TEXT,
  display_order INTEGER
);

CREATE TABLE IF NOT EXISTS scam_categories (
  category_code TEXT PRIMARY KEY,
  linked_lesson TEXT
);

CREATE TABLE IF NOT EXISTS daily_aggregates (
  date TEXT NOT NULL,
  region_code TEXT NOT NULL,
  scam_category TEXT NOT NULL,
  channel TEXT NOT NULL,
  source TEXT NOT NULL,
  report_count INTEGER NOT NULL,
  PRIMARY KEY (date, region_code, scam_category, channel, source)
);

CREATE TABLE IF NOT EXISTS alert_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT NOT NULL,
  title_en TEXT NOT NULL,
  title_hi TEXT NOT NULL,
  title_cg TEXT NOT NULL,
  summary_en TEXT NOT NULL,
  summary_hi TEXT NOT NULL,
  summary_cg TEXT NOT NULL,
  scam_category TEXT NOT NULL,
  region_scope TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  source_note TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS rate_limit_log (
  hashed_token TEXT NOT NULL,
  window_start TEXT NOT NULL,
  count INTEGER NOT NULL,
  PRIMARY KEY (hashed_token, window_start)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_agg_date ON daily_aggregates(date);
CREATE INDEX IF NOT EXISTS idx_reports_client_batch ON scam_reports(client_batch_id);
CREATE INDEX IF NOT EXISTS idx_rate_limit_window ON rate_limit_log(window_start);

-- Security: Enable Row Level Security (RLS) on all tables with zero public access policies.
ALTER TABLE scam_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE region_lookup ENABLE ROW LEVEL SECURITY;
ALTER TABLE scam_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_aggregates ENABLE ROW LEVEL SECURITY;
ALTER TABLE alert_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limit_log ENABLE ROW LEVEL SECURITY;

-- Revoke all direct privileges from public Supabase roles (anon, authenticated) if present
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
    REVOKE ALL ON ALL ROUTINES IN SCHEMA public FROM anon;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON ROUTINES FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM authenticated;
    REVOKE ALL ON ALL ROUTINES IN SCHEMA public FROM authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON ROUTINES FROM authenticated;
  END IF;
END $$;

